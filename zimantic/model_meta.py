# A pair of models is accepted when their probe embeddings are this close.
# FP32 and int8 exports of the same e5-small encoder score about 0.996 on
# average (minimum about 0.994), so 0.99 leaves room for quantization noise
# while rejecting a different fine-tune or architecture.
